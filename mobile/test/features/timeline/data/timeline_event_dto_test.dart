import 'package:cupid_mobile/features/timeline/data/timeline_event_dto.dart';
import 'package:cupid_mobile/features/timeline/domain/timeline_entry.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group('TimelineEventDto.fromJson', () {
    test('decodes a representative full payload', () {
      final dto = TimelineEventDto.fromJson({
        'id': 'ev-1',
        'coupleId': 'couple-1',
        'type': 'memory',
        'title': 'First fight, survived',
        'description': 'It was magical',
        'photoUrl': 'http://localhost:3000/uploads/photo.jpg',
        'icon': 'favorite',
        'createdAt': '2026-05-14T00:00:00.000Z',
      });

      expect(dto.id, 'ev-1');
      expect(dto.title, 'First fight, survived');
      expect(dto.type, TimelineEventType.memory);
      expect(dto.description, 'It was magical');
      expect(dto.photoUrl, 'http://localhost:3000/uploads/photo.jpg');
      expect(dto.icon, 'favorite');
      expect(dto.createdAt, DateTime.parse('2026-05-14T00:00:00.000Z'));
    });

    test('decodes absent optional fields as null', () {
      final dto = TimelineEventDto.fromJson({
        'id': 'ev-2',
        'title': 'No optionals',
        'createdAt': '2026-05-14T00:00:00.000Z',
      });

      expect(dto.description, isNull);
      expect(dto.photoUrl, isNull);
      expect(dto.icon, isNull);
      expect(dto.type, TimelineEventType.memory);
    });

    test('decodes explicit-null optional fields as null', () {
      final dto = TimelineEventDto.fromJson({
        'id': 'ev-3',
        'title': 'Explicit nulls',
        'description': null,
        'photoUrl': null,
        'icon': null,
        'createdAt': '2026-05-14T00:00:00.000Z',
      });

      expect(dto.description, isNull);
      expect(dto.photoUrl, isNull);
      expect(dto.icon, isNull);
    });

    test('decodes an unknown type as memory rather than throwing', () {
      final dto = TimelineEventDto.fromJson({
        'id': 'ev-4',
        'title': 'Mystery type',
        'type': 'something-new',
        'createdAt': '2026-05-14T00:00:00.000Z',
      });

      expect(dto.type, TimelineEventType.memory);
    });

    test('decodes milestone and system types', () {
      final milestone = TimelineEventDto.fromJson({
        'id': 'ev-5',
        'title': '1 Week Together!',
        'type': 'milestone',
        'createdAt': '2026-05-14T00:00:00.000Z',
      });
      final system = TimelineEventDto.fromJson({
        'id': 'ev-6',
        'title': 'System entry',
        'type': 'system',
        'createdAt': '2026-05-14T00:00:00.000Z',
      });

      expect(milestone.type, TimelineEventType.milestone);
      expect(system.type, TimelineEventType.system);
    });

    test('throws a typed decode failure when "id" is missing', () {
      expect(
        () => TimelineEventDto.fromJson({
          'title': 'No id',
          'createdAt': '2026-05-14T00:00:00.000Z',
        }),
        throwsA(isA<TimelineDecodeException>()),
      );
    });

    test('throws a typed decode failure when "id" is not a String', () {
      expect(
        () => TimelineEventDto.fromJson({
          'id': 42,
          'title': 'Non-string id',
          'createdAt': '2026-05-14T00:00:00.000Z',
        }),
        throwsA(isA<TimelineDecodeException>()),
      );
    });

    test('throws a typed decode failure when "title" is missing', () {
      expect(
        () => TimelineEventDto.fromJson({
          'id': 'ev-7',
          'createdAt': '2026-05-14T00:00:00.000Z',
        }),
        throwsA(isA<TimelineDecodeException>()),
      );
    });

    test('throws a typed decode failure when "title" is not a String', () {
      expect(
        () => TimelineEventDto.fromJson({
          'id': 'ev-8',
          'title': 7,
          'createdAt': '2026-05-14T00:00:00.000Z',
        }),
        throwsA(isA<TimelineDecodeException>()),
      );
    });
  });

  group('TimelineEntry.fromDto', () {
    test('derives isAutoGenerated from a non-memory type', () {
      final memory = TimelineEntry.fromDto(
        TimelineEventDto.fromJson({
          'id': 'ev-9',
          'title': 'A memory',
          'type': 'memory',
          'createdAt': '2026-05-14T00:00:00.000Z',
        }),
      );
      final milestone = TimelineEntry.fromDto(
        TimelineEventDto.fromJson({
          'id': 'ev-10',
          'title': 'A milestone',
          'type': 'milestone',
          'createdAt': '2026-05-14T00:00:00.000Z',
        }),
      );

      expect(memory.isAutoGenerated, isFalse);
      expect(milestone.isAutoGenerated, isTrue);
    });
  });

  group('TimelineDraft.toJson', () {
    test('emits exactly title, description, date, type, and icon', () {
      final draft = TimelineDraft(
        title: 'Our first date',
        date: DateTime.utc(2026, 5, 14),
        description: 'It was magical',
      );

      expect(draft.toJson(), {
        'title': 'Our first date',
        'description': 'It was magical',
        'date': '2026-05-14T00:00:00.000Z',
        'type': 'memory',
        'icon': 'favorite',
      });
    });

    test('omits description when absent and never sends photoUrl', () {
      final draft = TimelineDraft(
        title: 'No description',
        date: DateTime.utc(2026, 5, 14),
      );

      final json = draft.toJson();

      expect(json.containsKey('description'), isFalse);
      expect(json.containsKey('photoUrl'), isFalse);
      expect(json.keys, containsAll(['title', 'date', 'type', 'icon']));
    });
  });
}
