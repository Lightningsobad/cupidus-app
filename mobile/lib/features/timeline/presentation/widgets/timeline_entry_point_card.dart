/// Dashboard "Love Timeline" entry point (`ux/uiux-spec.md` section 1.1,
/// `Cupid Screens.dc.html` lines 341-347): renders the latest memory preview
/// (thumbnail, title, date and source) when at least 1 memory exists, or a
/// friendly prompt when empty.
class TimelineEntryPointCard extends StatelessWidget {
  const TimelineEntryPointCard({
    super.key,
    required this.onTap,
    this.latestEntry,
    this.repository,
  });

  final VoidCallback onTap;
  final TimelineEntry? latestEntry;
  final TimelineRepository? repository;

  @override
  Widget build(BuildContext context) {
    if (latestEntry != null) {
      return _TimelineEntryPointCardContent(
        onTap: onTap,
        entry: latestEntry,
      );
    }

    final repo = repository ??
        (getIt.isRegistered<TimelineRepository>() ? getIt<TimelineRepository>() : null);

    if (repo == null) {
      return _TimelineEntryPointCardContent(
        onTap: onTap,
        entry: null,
      );
    }

    return StreamBuilder<List<TimelineEntry>>(
      stream: repo.watchEntries(),
      builder: (BuildContext context, AsyncSnapshot<List<TimelineEntry>> snapshot) {
        final List<TimelineEntry>? entries = snapshot.data;
        final TimelineEntry? latest = (entries != null && entries.isNotEmpty) ? entries.first : null;
        return _TimelineEntryPointCardContent(
          onTap: onTap,
          entry: latest,
        );
      },
    );
  }
}

class _TimelineEntryPointCardContent extends StatelessWidget {
  const _TimelineEntryPointCardContent({
    required this.onTap,
    required this.entry,
  });

  final VoidCallback onTap;
  final TimelineEntry? entry;

  static final intl.DateFormat _dateFormat = intl.DateFormat('dd/MM/yyyy');

  String _formatSubtitle(TimelineEntry entry, BuildContext context) {
    final String dateStr = _dateFormat.format(entry.createdAt.toLocal());
    final String origin = entry.isAutoGenerated
        ? context.timelineAutoAdded
        : (entry.description?.isNotEmpty == true
            ? entry.description!
            : context.timelineMemoryDefault);
    return '$dateStr · $origin';
  }

  @override
  Widget build(BuildContext context) {
    final CupidColorTokens colors = context.cupidColors;
    final CupidTypographyTokens type = context.cupidType;
    final CupidPlatformTokens platformTokens = context.cupidPlatform;
    final AppL10n l10n = AppL10n.of(context);
    final TimelineEntry? item = entry;

    return Semantics(
      button: true,
      label: l10n.timeline_entry_point_card_label,
      child: InkWell(
        onTap: onTap,
        borderRadius: BorderRadius.circular(platformTokens.radiusCard),
        child: Container(
          constraints: BoxConstraints(minHeight: platformTokens.tapTarget),
          padding: const EdgeInsets.all(16),
          decoration: BoxDecoration(
            color: colors.colorSurface,
            borderRadius: BorderRadius.circular(platformTokens.radiusCard),
            boxShadow: platformTokens.elevationShadow,
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            mainAxisSize: MainAxisSize.min,
            children: <Widget>[
              // Header row
              Row(
                children: <Widget>[
                  ExcludeSemantics(
                    child: CupidIcon(
                      TimelineGlyphs.symbolFor('timeline') ?? Icons.timeline,
                      size: 19,
                      color: colors.colorAccentLilac,
                    ),
                  ),
                  const SizedBox(width: 8),
                  Expanded(
                    child: Text(
                      l10n.timeline_entry_point_card_label,
                      style: type.body.copyWith(
                        fontSize: 13,
                        fontWeight: FontWeight.w700,
                        color: colors.colorText,
                      ),
                    ),
                  ),
                  ExcludeSemantics(
                    child: CupidIcon(
                      CupidIcons.chevronRight,
                      size: 20,
                      color: colors.colorTextMuted,
                    ),
                  ),
                ],
              ),

              if (item != null) ...<Widget>[
                const SizedBox(height: 12),
                // Memory Content Row (50x50 thumbnail + title & date)
                Row(
                  children: <Widget>[
                    _buildThumbnail(item, colors, platformTokens),
                    const SizedBox(width: 12),
                    Expanded(
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: <Widget>[
                          Text(
                            item.title,
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                            style: type.body.copyWith(
                              fontSize: 14,
                              fontWeight: FontWeight.w700,
                              color: colors.colorText,
                            ),
                          ),
                          const SizedBox(height: 3),
                          Text(
                            _formatSubtitle(item, context),
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                            style: type.caption.copyWith(
                              fontSize: 11.5,
                              color: colors.colorTextMuted,
                            ),
                          ),
                        ],
                      ),
                    ),
                  ],
                ),
              ] else ...<Widget>[
                const SizedBox(height: 8),
                Text(
                  context.timelineEmptyHomePrompt,
                  style: type.caption.copyWith(
                    fontSize: 12,
                    color: colors.colorTextMuted,
                  ),
                ),
              ],
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildThumbnail(
    TimelineEntry item,
    CupidColorTokens colors,
    CupidPlatformTokens platformTokens,
  ) {
    if (item.photoUrl != null && item.photoUrl!.isNotEmpty) {
      return CupidTimelinePhoto(
        photoUrl: item.photoUrl!,
        width: 50,
        height: 50,
        fit: BoxFit.cover,
        borderRadius: platformTokens.radiusSmall,
        placeholder: _fallbackIcon(item, colors, platformTokens),
      );
    }
    return _fallbackIcon(item, colors, platformTokens);
  }

  Widget _fallbackIcon(
    TimelineEntry item,
    CupidColorTokens colors,
    CupidPlatformTokens platformTokens,
  ) {
    return Container(
      width: 50,
      height: 50,
      decoration: BoxDecoration(
        color: colors.colorSurfaceAlt,
        borderRadius: BorderRadius.circular(platformTokens.radiusSmall),
      ),
      child: Center(
        child: CupidIcon(
          TimelineGlyphs.symbolFor(item.icon) ?? TimelineGlyphs.fallbackFor(item.type),
          size: 22,
          color: colors.colorAccentPink,
        ),
      ),
    );
  }
}
