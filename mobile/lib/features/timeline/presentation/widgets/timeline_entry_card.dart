/// Icon-name-to-glyph mapping for [TimelineEntry.icon]
/// (`ux/uiux-spec.md` section 1.2 card row: "leading icon";
/// `coding-plan/phase-P5-timeline-screen.md` icon-string-to-glyph task).
/// Codepoints are confirmed in the bundled
/// `MaterialSymbolsRounded-Variable.ttf` cmap via fontTools, matching the
/// `CupidIcons` sourcing convention (never invented from memory of a
/// different icon font's PUA range). [symbolFor] returns `null` for any
/// name outside this known set -- including the backend's emoji defaults
/// `'💝'`/`'🏆'`, which only apply when a client omits `icon` (`TimelineDraft`
/// never does) -- so callers can fall back to a text glyph instead of
/// throwing or rendering `IconData(0)`.
abstract final class TimelineGlyphs {
  static const String _fontFamily = 'Material Symbols Rounded';

  static const Map<String, IconData> _named = <String, IconData>{
    'favorite': IconData(0xe87d, fontFamily: _fontFamily),
    'auto_awesome': IconData(0xe65f, fontFamily: _fontFamily),
    'timeline': IconData(0xe922, fontFamily: _fontFamily),
    'cake': IconData(0xe7e9, fontFamily: _fontFamily),
    'flight': IconData(0xe539, fontFamily: _fontFamily),
    'home': IconData(0xe88a, fontFamily: _fontFamily),
    'star': IconData(0xe838, fontFamily: _fontFamily),
    'celebration': IconData(0xea65, fontFamily: _fontFamily),
    'photo_camera': IconData(0xe3b0, fontFamily: _fontFamily),
    'image': IconData(0xe3f4, fontFamily: _fontFamily),
    'savings': IconData(0xe2eb, fontFamily: _fontFamily),
    'draw': IconData(0xe746, fontFamily: _fontFamily),
    'restaurant': IconData(0xe56c, fontFamily: _fontFamily),
    'hiking': IconData(0xe50a, fontFamily: _fontFamily),
    'beach_access': IconData(0xeb3e, fontFamily: _fontFamily),
    'pets': IconData(0xe91d, fontFamily: _fontFamily),
    'school': IconData(0xe80c, fontFamily: _fontFamily),
    'work': IconData(0xe8f9, fontFamily: _fontFamily),
    'broken_image': IconData(0xe3ad, fontFamily: _fontFamily),
    'wifi_off': IconData(0xe648, fontFamily: _fontFamily),
    'error': IconData(0xe000, fontFamily: _fontFamily),
    'refresh': IconData(0xe5d5, fontFamily: _fontFamily),
    'add_circle': IconData(0xe147, fontFamily: _fontFamily),
    'cloud_off': IconData(0xe2c1, fontFamily: _fontFamily),
  };

  /// Returns the mapped glyph for a known [name], or `null` when [name] is
  /// `null`, empty, or not in the known set.
  static IconData? symbolFor(String? name) {
    if (name == null || name.isEmpty) return null;
    return _named[name];
  }

  /// Per-type fallback glyph used when [TimelineEntry.icon] is `null` or not
  /// in [symbolFor]'s known set (every card has a leading icon --
  /// `ux/uiux-spec.md` section 1.2).
  static IconData fallbackFor(TimelineEventType type) {
    return switch (type) {
      TimelineEventType.memory => _named['favorite']!,
      TimelineEventType.milestone => _named['star']!,
      TimelineEventType.system => _named['auto_awesome']!,
    };
  }
}

/// A single Love Timeline card (`ux/uiux-spec.md` section 1.2 card row):
/// leading icon, title, trailing date, optional description, optional photo,
/// and an "auto-added" pill with no delete affordance for
/// [TimelineEntry.isAutoGenerated] entries (D-012 read-only auto-entries).
class TimelineEntryCard extends StatelessWidget {
  const TimelineEntryCard({super.key, required this.entry, this.accent});

  final TimelineEntry entry;

  /// Per-entry accent driving the leading icon (and, on the screen, the
  /// connector dot) -- the design source varies it per row. Defaults to pink
  /// for standalone use outside the timeline rail.
  final Color? accent;

  @override
  Widget build(BuildContext context) {
    final CupidColorTokens colors = context.cupidColors;
    final CupidTypographyTokens type = context.cupidType;
    final CupidPlatformTokens platformTokens = context.cupidPlatform;
    final IconData glyph =
        TimelineGlyphs.symbolFor(entry.icon) ??
        TimelineGlyphs.fallbackFor(entry.type);
    final String? description = entry.description;
    final String? photoUrl = entry.photoUrl;

    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 15),
      decoration: BoxDecoration(
        color: colors.colorSurface,
        borderRadius: BorderRadius.circular(platformTokens.radiusCard),
        boxShadow: platformTokens.elevationShadow,
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          Row(
            children: <Widget>[
              ExcludeSemantics(
                child: CupidIcon(
                  glyph,
                  size: 18,
                  color: accent ?? colors.colorAccentPink,
                ),
              ),
              const SizedBox(width: 9),
              Expanded(
                child: Text(
                  entry.title,
                  maxLines: 2,
                  overflow: TextOverflow.ellipsis,
                  style: type.body.copyWith(
                    fontSize: 14.5,
                    fontWeight: FontWeight.w800,
                    color: colors.colorText,
                  ),
                ),
              ),
              const SizedBox(width: 9),
              // `ux/uiux-spec.md` section 4 deviation: the design source's
              // 9.5px date size falls below the 11pt accessibility minimum,
              // so this is bumped to 12 rather than transcribed verbatim.
              Text(
                _dateFormat.format(entry.createdAt),
                style: type.labelMono.copyWith(
                  fontSize: 12,
                  color: colors.colorTextMuted,
                ),
              ),
            ],
          ),
          if (description != null && description.isNotEmpty) ...<Widget>[
            const SizedBox(height: 7),
            Text(
              description,
              style: type.caption.copyWith(
                fontSize: 12.5,
                height: 1.5,
                color: colors.colorTextMuted,
              ),
            ),
          ],
          if (photoUrl != null && photoUrl.isNotEmpty) ...<Widget>[
            const SizedBox(height: 11),
            ClipRRect(
              borderRadius: BorderRadius.circular(platformTokens.radiusSmall),
              child: Image.network(
                photoUrl,
                height: _photoHeight,
                width: double.infinity,
                fit: BoxFit.cover,
                loadingBuilder:
                    (
                      BuildContext context,
                      Widget child,
                      ImageChunkEvent? progress,
                    ) {
                      if (progress == null) return child;
                      return const TimelinePhotoPlaceholder();
                    },
                errorBuilder:
                    (
                      BuildContext context,
                      Object error,
                      StackTrace? stackTrace,
                    ) {
                      return const TimelinePhotoPlaceholder();
                    },
              ),
            ),
          ],
          if (entry.isAutoGenerated) ...<Widget>[
            const SizedBox(height: 10),
            _AutoAddedPill(
              colors: colors,
              type: type,
              platformTokens: platformTokens,
            ),
          ],
        ],
      ),
    );
  }
}

const double _photoHeight = 112;

/// Empty/failed photo frame, transcribed from the design source's
/// `<image-slot>` component: neutral placeholder surface, dashed ring, image
/// glyph, and the placeholder caption -- not a bare error icon.
class TimelinePhotoPlaceholder extends StatelessWidget {
  const TimelinePhotoPlaceholder({super.key});

  @override
  Widget build(BuildContext context) {
    final CupidColorTokens colors = context.cupidColors;
    final CupidTypographyTokens type = context.cupidType;
    final CupidPlatformTokens platformTokens = context.cupidPlatform;

    return Container(
      height: _photoHeight,
      width: double.infinity,
      decoration: BoxDecoration(
        color: colors.colorSurfaceAlt,
        borderRadius: BorderRadius.circular(platformTokens.radiusSmall),
      ),
      child: TimelineDashedBorder(
        color: colors.colorText.withValues(alpha: 0.35),
        radius: platformTokens.radiusSmall,
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: <Widget>[
            ExcludeSemantics(
              child: CupidIcon(
                TimelineGlyphs.symbolFor('image')!,
                size: 28,
                color: colors.colorText.withValues(alpha: 0.45),
              ),
            ),
            const SizedBox(height: 6),
            Text(
              context.timelinePhotoPlaceholder,
              style: type.caption.copyWith(
                fontSize: 13,
                fontWeight: FontWeight.w500,
                color: colors.colorText.withValues(alpha: 0.75),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

final intl.DateFormat _dateFormat = intl.DateFormat('dd/MM/yy');

class _AutoAddedPill extends StatelessWidget {
  const _AutoAddedPill({
    required this.colors,
    required this.type,
    required this.platformTokens,
  });

  final CupidColorTokens colors;
  final CupidTypographyTokens type;
  final CupidPlatformTokens platformTokens;

  @override
  Widget build(BuildContext context) {
    return Align(
      alignment: Alignment.centerLeft,
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 9, vertical: 4),
        decoration: BoxDecoration(
          color: colors.colorSurfaceAlt,
          borderRadius: BorderRadius.circular(platformTokens.radiusButton),
        ),
        child: Row(
          mainAxisSize: MainAxisSize.min,
          children: <Widget>[
            ExcludeSemantics(
              child: CupidIcon(
                TimelineGlyphs.symbolFor('auto_awesome')!,
                size: 12,
                color: colors.colorTextMuted,
              ),
            ),
            const SizedBox(width: 5),
            Text(
              AppL10n.of(context).timeline_auto_added_pill,
              style: type.caption.copyWith(
                fontSize: 10,
                color: colors.colorTextMuted,
              ),
            ),
          ],
        ),
      ),
    );
  }
}
