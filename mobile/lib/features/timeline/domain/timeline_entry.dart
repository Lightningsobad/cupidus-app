import 'package:cupid_mobile/features/timeline/data/timeline_event_dto.dart';

/// Wire-level event kind (`backend/src/modules/timeline/entities/
/// timeline-event.entity.ts` `TimelineEventType`). `system` exists on the
/// frozen contract but is not emitted by any current backend code path.
enum TimelineEventType { memory, milestone, system }

/// Timeline domain model consumed by P3+ (`architecture/solution.md` §2,
/// §4 Contracts And Integrations). Immutable value type: two entries with
/// the same field values are equal.
class TimelineEntry {
  const TimelineEntry({
    required this.id,
    required this.type,
    required this.title,
    required this.createdAt,
    this.description,
    this.photoUrl,
    this.icon,
  });

  /// Maps the wire [TimelineEventDto] onto the domain model. `createdAt`
  /// doubles as the memory's date -- the server has no separate date
  /// column, `date` on create simply overwrites `createdAt`.
  factory TimelineEntry.fromDto(TimelineEventDto dto) {
    return TimelineEntry(
      id: dto.id,
      type: dto.type,
      title: dto.title,
      createdAt: dto.createdAt,
      description: dto.description,
      photoUrl: dto.photoUrl,
      icon: dto.icon,
    );
  }

  final String id;
  final TimelineEventType type;
  final String title;
  final DateTime createdAt;
  final String? description;
  final String? photoUrl;
  final String? icon;

  /// Server-generated entries (pet-milestone listener, or any future
  /// non-`memory` type) render read-only with the UX "auto-added" pill and
  /// offer no delete affordance.
  bool get isAutoGenerated => type != TimelineEventType.memory;

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      (other is TimelineEntry &&
          other.id == id &&
          other.type == type &&
          other.title == title &&
          other.createdAt == createdAt &&
          other.description == description &&
          other.photoUrl == photoUrl &&
          other.icon == icon);

  @override
  int get hashCode => Object.hash(
    id,
    type,
    title,
    createdAt,
    description,
    photoUrl,
    icon,
  );
}
